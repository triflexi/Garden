#!/usr/bin/env bash
set -Eeuo pipefail
cd "$(dirname "$0")/.."
umask 077
exec 9>.deploy.lock
flock -n 9 || { echo 'A deployment is already running' >&2; exit 1; }
: "${API_IMAGE:?Set API_IMAGE to an immutable image tag}"
: "${WEB_IMAGE:?Set WEB_IMAGE to an immutable image tag}"
if [[ ! -e .env ]]; then
  : "${DEPLOY_HOST:?Set DEPLOY_HOST for automatic first deployment}"
  HTTP_PORT="${DEPLOY_HTTP_PORT:-80}" bash scripts/bootstrap.sh "${DEPLOY_PUBLIC_HOST:-$DEPLOY_HOST}"
fi
[[ -f .env && -r .env ]] || { echo 'The application .env must be a readable regular file.' >&2; exit 1; }
if [[ -n "${GRAFANA_PASSWORD:-}" ]]; then bash scripts/grafana-password.sh configure; fi
compose=(docker compose -f compose.yaml -f compose.prod.yaml)
export DEPLOY_PULL_POLICY=always
"${compose[@]}" config --quiet
"${compose[@]}" pull
# Compose 2.24.4 has no `run --pull`; apply the policy through the production file.
export DEPLOY_PULL_POLICY=never
if [[ -f .deploy-images.env ]]; then
  cp -- .deploy-images.env .previous-images.env
  bash scripts/backup.sh
fi
"${compose[@]}" up -d --wait --wait-timeout 120 --pull never db
"${compose[@]}" run --rm --no-deps migrate
started=true
if ! "${compose[@]}" up -d --no-build --pull never --remove-orphans; then
  started=false
fi
if [[ "$started" == true && -n "${GRAFANA_PASSWORD:-}" ]]; then
  if ! bash scripts/grafana-password.sh apply; then started=false; fi
fi
wait_for_health() {
  local attempt endpoint port
  for ((attempt=0; attempt<30; attempt++)); do
    if endpoint="$("${compose[@]}" port web 80)" && [[ -n "$endpoint" ]]; then
      endpoint="${endpoint%%$'\n'*}"
      port="${endpoint##*:}"
      if curl --fail --silent --show-error --max-time 5 "http://127.0.0.1:$port/api/health/ready" >/dev/null && curl --fail --silent --show-error --max-time 5 "http://127.0.0.1:$port/web-health" >/dev/null; then
        return 0
      fi
    fi
    sleep 2
  done
  return 1
}
if [[ "$started" == true ]] && wait_for_health; then
  printf 'API_IMAGE=%s\nWEB_IMAGE=%s\n' "$API_IMAGE" "$WEB_IMAGE" > .deploy-images.env.tmp
  mv -- .deploy-images.env.tmp .deploy-images.env
  echo 'Deployment healthy.'
  exit 0
fi
echo 'Health check failed. Rolling back application images.' >&2
if [[ -f .deploy-images.env ]]; then
  set -a
  # This file is generated by this script only after a successful deployment.
  # shellcheck source=/dev/null
  source .deploy-images.env
  set +a
  if "${compose[@]}" up -d --no-deps --no-build --pull never api web && wait_for_health; then
    echo 'Previous application images restored and healthy.' >&2
  else
    echo 'Rollback failed. Manual recovery is required; saved image references were retained.' >&2
  fi
else
  echo 'No previous deployment is available for rollback.' >&2
fi
exit 1
